def build_rows():
    rows = []
    for mon, data in [("04", APR), ("05", MAY)]:
        for day, rain, r1h, w0, w1, w2 in data:
            date = f"2026-{mon}-{day:02d}"
            daytime_rain = ("雨" in w0) or ("雨" in w1)  # 運行時間帯の降雨
            rows.append({
                "date": date,
                "rain_mm": rain,
                "rain_1h_max_mm": r1h,
                "wx_0_9": w0, "wx_9_15": w1, "wx_15_24": w2,
                "is_rain_day": rain >= 1.0,
                "is_heavy_rain_day": rain >= 10.0,
                "daytime_rain": daytime_rain,
            })
    return rows


def main():
    import pandas as pd
    df = pd.DataFrame(build_rows())
    df["date"] = pd.to_datetime(df["date"]).dt.date
    client = bigquery.Client(project=PROJECT)
    table_id = f"{PROJECT}.bus_gps_data.weather"
    job = client.load_table_from_dataframe(
        df, table_id,
        job_config=bigquery.LoadJobConfig(write_disposition="WRITE_TRUNCATE"))
    job.result()
    print(f"uploaded weather: {len(df)} rows -> {table_id}")
    print(df[df["is_rain_day"]][["date", "rain_mm", "daytime_rain"]].to_string(index=False))


if __name__ == "__main__":
    main()
